"""Write requirements-lock.txt: exact versions of every direct and transitive dependency
of requirements.txt and requirements-dev.txt, as installed now, plus the Python version.

    python scripts/lock_env.py            # write the lock from the current environment
    python -m avval.cli env-check         # compare an environment with the lock

Install the locked environment with `pip install -r requirements-lock.txt` on the Python
version recorded in it. The lock pins packages, not OS libraries or CPU features; the
runtime fingerprint stored with every campaign records platform and machine as well.
"""
from __future__ import annotations

import platform
import re
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _name(req: str) -> str:
    return re.split(r"[\s;<>=!~\[]", req.strip(), maxsplit=1)[0].lower()


def closure(names: list[str]) -> dict[str, str]:
    seen: dict[str, str] = {}
    todo = list(names)
    while todo:
        n = todo.pop()
        if n in seen:
            continue
        try:
            dist = metadata.distribution(n)
        except metadata.PackageNotFoundError:
            continue
        seen[n] = dist.version
        for req in dist.requires or []:
            if "extra ==" in req:
                continue
            todo.append(_name(req))
    return seen


def main() -> None:
    direct = []
    for f in ("requirements.txt", "requirements-dev.txt"):
        p = ROOT / f
        if p.exists():
            direct += [_name(x) for x in p.read_text().splitlines() if x.strip()
                       and not x.startswith("#")]
    pins = closure(direct)
    lines = ["# Generated by scripts/lock_env.py - exact environment for reruns.",
             f"# python=={platform.python_version()} ({platform.system()} {platform.machine()})",
             *[f"{n}=={v}" for n, v in sorted(pins.items())]]
    (ROOT / "requirements-lock.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"locked {len(pins)} packages")


if __name__ == "__main__":
    main()
